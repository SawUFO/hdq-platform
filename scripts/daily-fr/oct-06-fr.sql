<h2>Confort du consensus et aversion myope aux pertes</h2>
<p>La toile de fond générale est calme en surface. Yahoo Finance a rapporté le 5 octobre que l’indice S&amp;P 500 avait monté vendredi jusqu’à moins de 1&nbsp;% de son record, malgré des rendements obligataires à leur plus haut niveau en plus de 20 ans, après qu’un faible rapport sur l’emploi a réduit les attentes d’une hausse de taux de la Réserve fédérale cette année. Le Bureau of Labor Statistics a fait état d’une hausse de 29&nbsp;000 emplois pour septembre. Le rendement des obligations du Trésor américain à 10 ans se situait près de 5,3&nbsp;% le 5 octobre.</p>
<p>Sean McLaughlin, stratège en chef des options chez All Star Charts, a déclaré à Yahoo Finance&nbsp;: «&nbsp;Le marché avait toutes les raisons de baisser, il ne l’a pas encore fait, et j’ai l’impression que le temps lui est compté.&nbsp;» Les données de FactSet montrent que 60&nbsp;% des titres du S&amp;P 500 portent désormais une recommandation d’achat des analystes de Wall Street, un sommet inégalé. Un consensus aussi confortable donne aux investisseurs une preuve sociale que rien ne doit changer, ce qui prépare le terrain au comportement moutonnier.</p>
<p>Shlomo Benartzi et Richard Thaler ont nommé, dans un article de 1995 du Quarterly Journal of Economics, la combinaison qui compte ici&nbsp;: l’aversion myope aux pertes. Les investisseurs qui vérifient souvent leurs résultats subissent davantage de pertes et exigent donc une plus grande compensation pour porter du risque. Un marché qui oscille dans une bande de 4,9&nbsp;% offre à celui qui vérifie souvent de nombreuses petites pertes à compter et peu de gains nets.</p>
<p>Terrance Odean, dans une étude de 1998 du Journal of Finance portant sur des comptes de courtage de détail, a constaté que les investisseurs réalisaient 14,8&nbsp;% de leurs gains latents, mais seulement 9,8&nbsp;% de leurs pertes latentes, ce qu’on appelle l’effet de disposition. Dans un marché où les 27 dernières clôtures se situent toutes sous le sommet d’août, l’attrait de conserver ce qui baisse et de vendre ce qui monte ne manque pas de matière. Le taux directeur de la Banque du Canada est de 2,25&nbsp;% et le rendement des obligations du gouvernement du Canada à 10 ans dépassait 4&nbsp;% le 1er octobre, si bien que les liquidités et les obligations rivalisent avec les actions pour l’attention au même moment.</p>
