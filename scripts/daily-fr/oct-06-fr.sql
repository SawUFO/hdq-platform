<h2>L’aversion aux pertes joue aussi dans les marchés calmes</h2>
<p>Dans leur article de 1979 sur la théorie des perspectives, publié dans Econometrica, Kahneman et Tversky ont montré que les gens évaluent les résultats comme des gains ou des pertes par rapport à un point de référence plutôt que comme une richesse finale. Dans une suite publiée en 1992 dans le Journal of Risk and Uncertainty, Tversky et Kahneman ont estimé le coefficient médian d’aversion aux pertes à environ 2,25, ce qui signifie qu’une perte pèse environ 2,25 fois plus lourd qu’un gain de même taille.</p>
<p>Pour bien des détenteurs d’actions canadiennes, le point de référence est le dernier sommet dont ils se souviennent. Le TSX a clôturé sous son niveau du 25 août à chacune des 27 séances suivantes, et l’indice a reculé de 4,9&nbsp;% entre cette clôture et le creux du 1er octobre. Un manque à gagner de 3,9&nbsp;% ne fait pas la une. Il s’enregistre bien comme une perte par rapport au point de référence, et l’aversion aux pertes veut que cet enregistrement pèse plus lourd que ne le ferait un gain de même taille.</p>
<p>Le TSX a regagné 19,3&nbsp;% de son recul du sommet au creux. L’indice a baissé par glissement lent plutôt que par rupture, une forme qui donne aux investisseurs le temps de réévaluer sans jamais leur offrir un événement unique à blâmer. Le TSX a clôturé sous le sommet du 25 août aux 27 séances qui ont suivi.</p>
