<p>Le taux prescrit n’est pas fixé à la discrétion de l’ARC. Il correspond au rendement moyen des bons du Trésor du gouvernement du Canada à 90 jours du premier mois du trimestre précédent, arrondi au point de pourcentage supérieur. Il se maintient à 3 % depuis le troisième trimestre de 2025 parce que les taux à court terme sont restés assez bas pour que l’arrondi s’y maintienne.</p>
<p>Deux développements cette semaine mettent ce mécanisme sous pression. Les tarifs de rétorsion du Canada sur 27,6 G$ de produits américains sont entrés en vigueur le 8 septembre, avec des droits pouvant atteindre 50 % sur l’acier, l’aluminium et diverses catégories de biens de consommation. Deux jours plus tôt, la Banque du Canada a maintenu son taux directeur à 2,25 % pour une septième décision d’affilée, mais a assorti ce maintien d’un avertissement explicite&nbsp;: les coûts liés aux tarifs et la hausse des prix du pétrole augmentent le risque que l’inflation grimpe au lieu de se stabiliser près de la cible de 2 %, et la Banque est prête à remonter les taux de nouveau si cela se propage aux prix courants.</p>
<h2>Le lien mécanique entre les tarifs et le taux prescrit</h2>
<p>Une hausse de taux de la Banque du Canada à la décision du 28 octobre ferait grimper les rendements des bons du Trésor à court terme, soit précisément l’intrant à partir duquel le taux prescrit est construit. Un prêt établi sous le taux actuel de 3 % conserve ce taux pour toute sa durée, pourvu que l’intérêt soit payé annuellement au plus tard le 30 janvier de l’année suivante. Un prêt établi après le rajustement du taux n’en bénéficie pas rétroactivement.</p>
