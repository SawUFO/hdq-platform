<p>Le TSX a clôturé en baisse d’environ un tiers de point de pourcentage, près de 36&nbsp;000, même si Canadian Natural Resources et Suncor Energy ont toutes deux progressé de plus de 1&nbsp;% sur la flambée du pétrole. Depuis six mois, la réaction habituelle du TSX à une escalade autour d’Hormuz a été un rallye mené par l’énergie, assez large pour compenser la faiblesse ailleurs sur l’indice. Aujourd’hui, cette séquence s’est brisée. L’énergie a fait exactement ce qu’elle fait depuis le début de la guerre&nbsp;: elle a grimpé sur la manchette. L’indice a quand même reculé.</p>
