<h2>Ce que prédit l’ancrage, et ce qui s’est produit</h2>
<p>Kahneman et Tversky, dans leur publication de 1974, ont décrit l’ancrage comme la tendance à fixer un point de référence tôt, puis à s’en écarter de façon insuffisante à mesure que de nouvelles informations arrivent. Appliqué ici&nbsp;: le niveau de base du VIX durant cette période n’a jamais été un niveau calme, d’avant conflit. Il était déjà élevé après sept mois de fermeture active du détroit d’Ormuz, entamée le 28 février. Chaque escalade subséquente, y compris celle qui a supprimé une route de contournement de plusieurs millions de barils, est mesurée comme un léger écart par rapport à un ancrage déjà élevé, plutôt que comme le choc autonome qu’elle représenterait isolément.</p>
