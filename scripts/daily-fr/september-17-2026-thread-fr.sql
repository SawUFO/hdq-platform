<h2>Une formule abandonnée, un constat publié</h2>

<p>Mercredi, la Fed a relevé sa fourchette cible de 25 points de base, à 3,75&nbsp;% à 4,00&nbsp;%, sa première hausse depuis juillet 2023. Les stratèges ont relevé un changement précis dans le communiqué qui accompagnait la décision&nbsp;: la formule qui attribuait auparavant la fermeté de l’inflation à un choc d’offre lié aux prix de l’énergie avait disparu. Le communiqué de septembre qualifiait désormais la croissance des prix de simplement élevée. Ce n’est pas un hasard de formulation. Parler d’un choc d’offre suppose qu’il finit par passer. Parler d’une inflation élevée suppose qu’elle ne se résorbe pas d’elle-même.</p>

<p>Le même jour, la Banque du Canada a publié le compte rendu de sa décision du 2 septembre de maintenir son taux à 2,25&nbsp;%. Les membres du Conseil de direction avaient examiné le même facteur, la hausse des prix de l’essence attribuable au conflit touchant l’Iran, et sont arrivés à un constat plus restreint&nbsp;: peu d’indices d’une propagation généralisée de la hausse des prix de l’énergie aux autres biens et services au Canada. Le conseil a indiqué qu’il agirait au moyen de plusieurs hausses si cette propagation se manifestait. Elle ne s’est pas encore manifestée, selon sa propre analyse.</p>

<p>Deux banques centrales, un même choc énergétique, et une divergence le même jour sur la façon de le nommer. La Fed l’a jugé assez durable pour justifier une hausse. La Banque du Canada l’a jugé encore suffisamment contenu pour justifier d’attendre des preuves qui ne figuraient pas dans les données qu’elle avait examinées trois jours plus tôt.</p>

<h2>Le choc lui-même s’est mis à se résorber dès le matin</h2>

<p>Le Brent a reculé de 1,69&nbsp;% jeudi, à 104,04&nbsp;$&nbsp;US, et le West Texas Intermediate a cédé environ 1,06&nbsp;% à environ 101,34, alors que du brut saoudien additionnel acheminé via Oman et une réparation plus rapide que prévu des infrastructures d’exportation saoudiennes ont atténué la crainte d’approvisionnement qui avait poussé les deux référentiels vers des sommets de quatre mois plus tôt cette semaine. Ce repli marque une deuxième séance consécutive de détente, et non un simple accroc d’une journée.</p>

<p>L’or a suivi une trajectoire plus inhabituelle. Le cours au comptant est passé de plus de 4&nbsp;360&nbsp;$&nbsp;US avant la décision de la Fed à près de 4&nbsp;240 aussitôt après le signal restrictif, puis a remonté à environ 4&nbsp;307 jeudi, en hausse d’environ 1,0&nbsp;% sur la journée, même si le dollar américain se situait à son plus haut niveau en sept semaines. Cette remontée ne provient pas du mécanisme habituel des taux et du dollar, puisque les deux ont évolué contre l’or. Elle témoigne plutôt d’une demande de diversification et de nature géopolitique, qui persiste peu importe le sens que prend une décision de taux donnée. L’argent a suivi le mouvement, en hausse de 1,6&nbsp;% à 63,96.</p>

<p>L’indice composé S&amp;P/TSX raconte la même histoire sur les 23 dernières séances&nbsp;: un sommet à la fin août, un recul pénible de six semaines qui a touché son creux le jour de la hausse de la Fed, puis une reprise partielle jeudi, les métaux de base ayant tiré vers le haut l’ensemble des titres miniers.</p>

