<h2>La Banque d’Angleterre a conditionné sa prochaine décision à un prix du pétrole dicté par la politique</h2>
<p>La Banque d’Angleterre a relevé son taux directeur de 3,75&nbsp;% à 4&nbsp;% par 8 voix contre 1, sa première hausse depuis 2023, un membre ayant voté pour une hausse plus forte. Le gouverneur Bailey a déclaré que cette décision ne devait pas être interprétée comme la première d’une longue série, et la banque a indiqué que la forte baisse des prix de l’énergie après les élections de mi-mandat, si elle se maintient, pourrait limiter de nouvelles hausses. Elle prévoit aussi que l’inflation atteindra 5&nbsp;% d’ici le milieu de 2027.</p>
<p>La condition repose sur un prix qui a bougé sur une lecture politique. La rubrique Géopolitique a établi mercredi matin qu’aucun cessez-le-feu n’est en vigueur et que des mines avaient été signalées au détroit d’Ormuz. En fin de journée jeudi, le WTI se situait près de 90&nbsp;$, en hausse d’environ 3&nbsp;% par rapport à son cours de clôture de 88,12&nbsp;$, sur fond de doutes quant à un accord entre les États-Unis et l’Iran, et le Brent se situait près de 97&nbsp;$ contre 94,62&nbsp;$.</p>
<p>La Banque du Canada est exposée au même facteur. Elle a relevé son taux directeur à 2,5&nbsp;% le 28 octobre, alors que l’inflation fondamentale était inférieure à 2&nbsp;% et que 41&nbsp;200 emplois avaient été perdus, une décision que la rubrique Économie a rattachée aux prévisions de la banque, et sa prochaine décision, le 9 décembre, fixe aussi l’échéance de la fenêtre de fractionnement du revenu que la rubrique Fiscalité et patrimoine a signalée par rapport au taux prescrit de 3&nbsp;%. Les deux calendriers passent désormais par un prix du pétrole que deux jours de politique ont fait reculer de 8,7&nbsp;%, puis remonter d’environ 3&nbsp;%, sans cessez-le-feu en place.</p>
<h2>Toronto a absorbé environ la moitié de la perte parce que le pétrole et l’or ont évolué en sens inverse</h2>
<p>L’indice composé S&amp;P/TSX a progressé de 2,28&nbsp;% mercredi alors que le WTI reculait de 8,29&nbsp;%, et affichait un recul de 2,13&nbsp;% à 15 h 30 HE jeudi alors que le WTI se redressait, ce qui laisse l’indice environ 4&nbsp;% sous son record d’août de 37&nbsp;069,11.</p>
