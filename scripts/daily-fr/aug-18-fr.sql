<p>Sur la seule base des données sur l’inflation, la décision du 2 septembre se lit comme l’un des appels les plus mécaniques auxquels la Banque a fait face cette année. L’Enquête sur la population active de juillet a montré un taux de chômage se maintenant près de ses creux récents, la croissance du PIB du deuxième trimestre suit une trajectoire annualisée supérieure à 3&nbsp;%, et chaque mesure fondamentale se situe à quelques pas de 2&nbsp;%. Le cadre même de la Banque, qui accorde plus de poids aux mesures fondamentales qu’au chiffre global, précisément parce qu’elles filtrent la volatilité énergétique, pointe vers un taux directeur inchangé.</p>
<p>Ce qui complique cette lecture, ce n’est pas le rapport sur l’inflation. C’est la réaction du marché obligataire au même conflit au Moyen-Orient qui alimente d’abord le chiffre de l’essence. Le cessez-le-feu de 60 jours entre les États-Unis et l’Iran a expiré lundi sans prolongation, et le rendement de l’obligation du Trésor américain à 30 ans a grimpé à 5,333&nbsp;% dans les échanges de mardi, sa plus haute clôture depuis juin 2007, alors que les investisseurs intégraient dans la dette à longue échéance une période prolongée de prix de l’énergie élevés et de risque géopolitique.</p>
<h2>Pourquoi le marché obligataire compte plus que le taux directeur ici</h2>
<p>Les taux hypothécaires fixes canadiens suivent le rendement de l’obligation du gouvernement du Canada à cinq ans, pas directement le taux directeur de la Banque du Canada. Le rendement du GdC à cinq ans a clôturé à 3,29&nbsp;% le 14 août, et les marchés obligataires mondiaux ne bougent pas de façon isolée. Une liquidation soutenue des obligations du Trésor américain à longue échéance entraîne les rendements canadiens avec elle par arbitrage et flux de capitaux transfrontaliers, peu importe ce que la Banque du Canada annonce le 2 septembre.</p>
<p>C’est le mécanisme qui mérite d’être suivi au cours des deux prochaines semaines. La Banque peut maintenir le taux directeur exactement là où les données sur l’inflation suggèrent qu’elle devrait le faire, et les coûts de renouvellement hypothécaire des ménages canadiens peuvent tout de même grimper si l’impasse à Ormuz continue de pousser les rendements obligataires mondiaux à la hausse. L’outil de politique monétaire et le résultat du marché ne sont pas le même levier, et le rapport sur l’inflation de juillet, aussi calme soit-il sous le chiffre de l’essence, ne règle pas lequel des deux dominera tout au long de la saison de renouvellement de l’automne.</p>
