<p>Des tarifs en vertu de l’article 338 de 50&nbsp;% sur près de 20 milliards de dollars d’exportations canadiennes entrent en vigueur à 0&nbsp;h&nbsp;01, heure de l’Est, mercredi, calculés selon la date à laquelle les produits sont entrés à la frontière américaine plutôt que la date de leur expédition, et sans exemption de l’ACEUM. Le bureau Fiscalité et patrimoine de HDQ a signalé cette échéance ce matin. Ce que le bureau ne pouvait pas encore voir, c’est la façon dont le marché des devises l’évalue&nbsp;: essentiellement pas du tout. L’USD/CAD s’est établi à 1,3871 mardi, en baisse de deux centièmes de pourcent par rapport à lundi, essentiellement stable à l’approche d’un choc tarifaire que VT Markets estime pouvoir faire bouger le huard de plus de deux pour cent si l’épisode tarifaire de 2018 sert de guide.</p>

<p>Ce calme ressemble moins à de la confiance qu’à de la distraction. Le même après-midi qui a produit la déclaration de Trump sur Ormuz et le nouveau sommet du taux à 30 ans a aussi produit un dollar canadien véritablement calme, un TSX entraîné près de 140 points dans le rouge par la faiblesse des minières aurifères même si son sous-indice de l’énergie a progressé, et une réévaluation du marché obligataire qui restreint la marge de manœuvre dont dispose la Banque du Canada pour assouplir sa politique lors de sa décision du 2 septembre, peu importe ce que l’IPC de juillet, plus chaud que prévu, a déjà fait à ce calcul.</p>

<p>La séance de l’or, évaluée heure par heure, retrace directement le relais&nbsp;: ferme pendant la matinée sur les manchettes d’Ormuz, puis cédant du terrain une fois que la publication du taux à 30 ans a pris le contrôle de la séance peu après midi.</p>

