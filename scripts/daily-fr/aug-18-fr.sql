<h2>L’effet de disposition, inversé</h2>
<p>La conclusion classique de Shefrin et Statman est que les investisseurs vendent trop tôt leurs positions gagnantes et conservent trop longtemps leurs positions perdantes, ancrés à leur prix de base plutôt qu’à l’information actuelle. Le mécanisme à l’œuvre cette semaine est une variante du même biais. Les clients ne sont pas ancrés à ce qu’ils ont payé pour leur exposition aux actions canadiennes il y a un an. Ils sont ancrés au sommet record que l’indice a touché jeudi dernier.</p>
<p>Tout mouvement à la baisse par rapport à cet ancrage s’enregistre comme une perte, même si la position demeure spectaculairement profitable sur un horizon de douze mois. C’est de l’encadrement étroit&nbsp;: le point de référence qui compte émotionnellement est le sommet le plus récent, pas le gain réel dans le compte. La littérature de recherche appelle le comportement qui en résulte la « get-evenitis » lorsqu’il s’applique aux positions perdantes. La version qui apparaît après une course record en est l’image miroir, une ruée pour verrouiller un gain dès que celui-ci cesse de croître.</p>
