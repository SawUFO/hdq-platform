<h2>Pourquoi le récit tarifaire n’explique plus le récit des rendements</h2>

<p>Cela importe parce que l’analyse du bureau Économie des deux dernières séances, selon laquelle les rendements canadiens intègrent le risque commercial Ottawa-Washington, ne survit que partiellement à la clôture d’aujourd’hui. Une partie des 5,6 points de base de jeudi correspond véritablement à une réévaluation mondiale de la prime de terme, sans lien avec le différend tarifaire, et se serait produite pour les obligations canadiennes peu importe la suite des événements entre Ottawa et Washington. Cette portion ne s’effacera pas si le différend commercial s’apaise. Il s’agit d’un événement de plomberie du marché obligataire, non d’un événement lié aux attentes d’inflation.</p>

