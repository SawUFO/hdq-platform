<p>Les salaires indiquent le contraire. Le salaire horaire moyen des employés permanents a augmenté de 2,3&nbsp;% sur un an, contre 2,0&nbsp;% en août, et l’inflation annuelle s’établissait à 3&nbsp;% en août, face à un taux directeur de 2,25&nbsp;%. Cela concorde avec une tarification des swaps qui maintient toujours une hausse complète de 25 points de base d’ici décembre. Le marché a déplacé les probabilités d’octobre, pas la destination.</p>
