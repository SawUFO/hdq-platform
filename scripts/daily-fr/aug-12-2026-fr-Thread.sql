<p>Le rendement de l’obligation gouvernementale canadienne à 10 ans s’est détendu à environ 3,69&nbsp;% mercredi après-midi, en baisse par rapport à la clôture de mardi près de 3,75&nbsp;%, le sommet de 26 mois autour duquel le pupitre Économie a bâti sa couverture ce matin. Le mouvement découle directement de la publication américaine. L’IPC global correspondant aux attentes et l’inflation de base ralentissant, les marchés à terme ont réduit les probabilités d’une hausse de la Fed en septembre, et le rendement du Trésor américain à 10 ans s’est détendu vers 4,67&nbsp;%, contre un niveau plus près de 4,7&nbsp;% plus tôt dans la semaine. Les deux courbes ont bougé de concert parce qu’elles sont mécaniquement liées.</p>

