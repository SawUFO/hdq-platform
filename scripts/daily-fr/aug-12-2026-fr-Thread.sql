<h2>L’or, pas le pétrole, est maintenant le secteur moteur des records du TSX</h2>

<p>La clôture record de mardi, celle dont le pupitre Marchés a traité ce matin, reposait sur l’énergie et les industrielles. Le relèvement de la cible d’Air Canada et la croissance des revenus de commissions de Brookfield Asset Management ont porté un rallye étroit, pendant que les financières évoluaient de façon mitigée à baissière. En après-midi mercredi, le classement des secteurs s’était complètement inversé. Le TSX composé a ajouté 122 points de plus pour se négocier près de 36&nbsp;598, un quatrième record consécutif, mais l’or a mené tous les secteurs avec une hausse de 1,4&nbsp;%, suivi des matériaux à 1,0&nbsp;% et des financières à 0,6&nbsp;%. L’immobilier, les technologies de l’information et les télécommunications ont été les retardataires, en baisse de 0,3&nbsp;% à 0,7&nbsp;%. L’énergie, moteur de mardi, n’a figuré à aucune des deux extrémités du classement de mercredi.</p>

<p>Le catalyseur est le même que celui qui fait bouger le marché obligataire. Le cours au comptant de l’or a grimpé vers 4&nbsp;425&nbsp;$ l’once, s’approchant d’un sommet de 10 semaines, alors que le ralentissement de l’IPC a réduit les probabilités d’une hausse de la Fed en septembre et renforcé un contexte de taux plus favorable à un actif ne générant pas de rendement. La demande des banques centrales vient s’ajouter à l’histoire des taux : la banque centrale de Chine a ajouté environ 20 tonnes à ses réserves en juillet, un 21e mois consécutif d’achats. Le résultat décevant de Franco-Nevada, l’histoire de biais d’ancrage dont le pupitre Comportement a traité ce matin, n’a pas empêché l’ensemble du secteur de l’or de progresser. Des producteurs plus modestes, dont Aris Mining et I-80 Gold, ont affiché certains des gains les plus importants de la séance.</p>

<p>L’implication pour la séance de demain découle directement des données sectorielles. La séquence de records du TSX a changé de dépendance sans changer de forme.</p>

