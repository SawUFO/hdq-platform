<h2>La courbe canadienne suit la courbe américaine</h2>
<p>Depuis le 4 août, le rendement canadien à deux ans a monté de 53 points de base, de 2,83&nbsp;% à 3,36&nbsp;%. Le rendement américain à deux ans a monté de 50, de 4,20&nbsp;% à 4,70&nbsp;%. Les variations quotidiennes des deux rendements affichent une corrélation de 0,68 sur cette période, selon un calcul de HDQ à partir de données de la Banque du Canada et de la Banque de réserve fédérale de Saint-Louis.</p>
