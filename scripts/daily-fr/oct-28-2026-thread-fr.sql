<h2>Deux dissidences à la Fed remettent l’ancien écart en jeu</h2>
<p>La Fed a maintenu sa fourchette de 3,75&nbsp;% à 4,00&nbsp;% par un vote de 10 contre 2. La gouverneure Lisa Cook et la présidente de la Fed de Cleveland, Beth Hammack, ont exprimé leur dissidence, toutes deux préférant une hausse d’un quart de point. Le point médian de cette fourchette se situe 137,5 points de base au-dessus du nouveau taux de la Banque du Canada, contre 162,5 avant ce matin. Une hausse de la Fed rétablit l’ancien chiffre.</p>
<p>Le marché obligataire s’était déjà ajusté au nouvel écart&nbsp;: l’écart de rendement se situe à moins de quatre points de base de 137,5 et à 28 sous son sommet de 162 du 9 octobre. Ce qui reste est une symétrie. Le marché demande à la Banque 91 points de base de resserrement supplémentaire et à la Fed environ 83, d’après le rendement américain à deux ans de 4,70&nbsp;% de mardi. Les prix du marché reflètent pour le Canada une politique presque aussi restrictive que pour les États-Unis.</p>
<p>La devise n’a accordé aucun crédit à la hausse. Le taux quotidien de la Banque du Canada était de 1,4036 par dollar américain contre 1,4038 mardi, et l’indice composé S&amp;P/TSX a clôturé à 36&nbsp;265,09, en hausse de 0,3&nbsp;%, dans la fourchette de 35&nbsp;584,50 à 36&nbsp;325,00 de ses douze dernières clôtures.</p>
<p>Le changement tient à l’endroit où regarder. La Banque a dit qu’elle procéderait avec prudence, et deux votants de la Fed ont demandé à leur comité de bouger. Selon la tendance observée depuis août, le prochain mouvement important des taux canadiens à court terme est plus susceptible d’être dicté par le calendrier des données américaines que par quoi que ce soit de dit à Ottawa.</p>
