<h2>Ce que Warsh a réellement dit, et pourquoi l’or a bougé plus que les actions</h2>

<p>Statistique Canada a livré vendredi matin le chiffre qu’attendait le pupitre Économie. Le PIB réel a progressé de 0,8&nbsp;% au deuxième trimestre, un rythme annualisé de 3,3&nbsp;% qui a dépassé la propre prévision de juillet de la Banque du Canada, fixée à 2,5&nbsp;%, et qui marque la croissance trimestrielle la plus rapide depuis le début de 2023. Une révision de routine a également transformé la contraction déclarée du premier trimestre en légère expansion annualisée de 0,3&nbsp;%, ce qui rend désormais caduc le débat sur la récession technique qui planait sur Bay Street depuis mai.</p>

<p>Le TSX a ouvert en hausse sur cette donnée et s’est brièvement négocié au-dessus de la clôture de jeudi. Puis, à 10&nbsp;h HE, Warsh a pris la parole à Jackson Hole pour ses premières remarques approfondies depuis son entrée en fonction en mai, affirmant que la tendance sous-jacente de l’inflation ne s’était pas véritablement améliorée, que la stabilité des prix demeurait la priorité absolue de la Fed, et que les probabilités d’une hausse en septembre avaient augmenté. Les négociateurs ont réagi en faisant grimper à 57&nbsp;% la probabilité implicite d’une hausse de la Fed lors de la réunion de septembre, en forte hausse par rapport au niveau observé en matinée.</p>

<p>Ces mêmes onze mots ont fait bouger quatre actifs selon quatre ampleurs différentes, et l’écart entre eux constitue le signal le plus utile pour un portefeuille exposé de façon significative aux actions canadiennes et aux métaux précieux.</p>

