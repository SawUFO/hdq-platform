<h2>Le piège de l’IMR que la plupart des conseillers n’ont pas modélisé</h2>
<p>L’impôt minimum de remplacement (IMR) repose sur un calcul parallèle que la plupart des clients ne voient jamais jusqu’à ce qu’il s’applique à eux. Aux fins de l’IMR, 100&nbsp;% d’un gain en capital est inclus dans l’assiette fiscale, et non les 50&nbsp;% habituels. Ce montant est soumis à un taux fédéral d’IMR de 20,5&nbsp;% et à une exemption de base de 173&nbsp;206&nbsp;$, indexée chaque année et fondée sur le seuil de la quatrième tranche d’imposition fédérale de l’année d’imposition 2024.</p>
