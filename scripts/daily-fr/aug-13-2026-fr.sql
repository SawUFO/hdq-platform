<p>Les producteurs d’énergie canadiens établissent le prix de leur production directement en fonction des références Brent et WTI, et le secteur porte une prime de risque géopolitique depuis le début de la perturbation dans le détroit d’Hormuz à la fin de février. Cette prime repose sur un argument lié à l’offre&nbsp;: le propre rapport de l’AIE montre que l’offre pétrolière mondiale devrait maintenant reculer de 4,3 millions de barils par jour en 2026, la production du Golfe se situant toujours à 8,3 millions de barils par jour sous les niveaux d’avant-guerre, même après une reprise partielle en juillet.</p>
