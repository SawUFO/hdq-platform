<p>Les travaux de 1974 de Kahneman et Tversky sur le jugement en contexte d’incertitude décrivaient la représentativité&nbsp;: les gens évaluent une nouvelle information selon qu’elle correspond ou non à un schéma mental déjà actif, plutôt qu’en soupesant de façon indépendante ce que la preuve devrait changer. En mai, le schéma actif était « la perturbation par l’IA menace les marges des logiciels », renforcé par un abaissement de la cote par Rothschild and Co Redburn en juillet, qui citait les outils d’IA pour petites entreprises de Meta comme une menace concurrentielle pour Shopify. La hausse des coûts s’inscrivait parfaitement dans ce schéma et a été sanctionnée.</p>

