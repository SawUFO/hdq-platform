<h2>Ce qui se fige et ce qui ne se fige pas</h2>

<p>Un prêt à taux prescrit porte le taux en vigueur le jour où il est consenti, et ce, pour toute la durée du prêt, peu importe ce qui arrive au taux par la suite, pourvu que l’emprunteur paie l’intérêt annuellement et règle l’intérêt de chaque année dans les 30 jours suivant la fin de cette année-là. Un seul manquement à ce délai de 30 jours suffit pour que l’ARC attribue de nouveau au prêteur tout le revenu de placement tiré du prêt, pour cette année-là et toutes les suivantes. Le mécanisme récompense l’octroi de capital avant une réinitialisation du taux, et non après.</p>

<p>Cela s’applique aux trois structures qui utilisent le taux prescrit pour le fractionnement du revenu&nbsp;: un prêt direct à un conjoint ou conjoint de fait à revenu moindre, un prêt à une fiducie familiale qui distribue le revenu à des bénéficiaires dans des tranches d’imposition inférieures, y compris des enfants mineurs, et le taux PODD des sociétés pour les SPCC ayant des actionnaires non-résidents liés. Chacune se fige séparément au taux en vigueur au moment où ce prêt précis est consenti. Une famille qui a mis de côté une stratégie planifiée de fractionnement du revenu a une raison bien réelle d’agir avant le 31 décembre plutôt qu’au cours de la nouvelle année.</p>

