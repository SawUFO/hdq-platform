<h2>L’heuristique de disponibilité fonctionne dans les deux sens</h2>

<p>Les travaux d’Amos Tversky et de Daniel Kahneman sur l’heuristique de disponibilité, publiés en 1973, ont montré que les gens jugent la probabilité d’un événement selon la facilité avec laquelle des exemples leur viennent à l’esprit. Ce constat s’applique généralement à la surréaction&nbsp;: un titre récent et marquant rend un événement plus probable en apparence que ne le justifie le taux de base réel. Le même mécanisme fonctionne à l’inverse, et cette direction reçoit beaucoup moins d’attention dans les conversations avec les clients.</p>

<p>Le conflit entre les États-Unis et l’Iran est entré cette semaine dans son septième mois, mais le précédent échange de tirs remontait à plus d’un mois. Trois semaines sans manchette suffisent pour qu’un conflit toujours actif s’efface de l’esprit d’un investisseur, même si rien n’a changé sur le fond. La montée stable et peu volatile de l’or vers 4&nbsp;700&nbsp;$ ne prouvait pas que le risque lié au détroit d’Ormuz s’était résorbé. Elle prouvait que ce risque avait cessé d’être présent à la mémoire, ce qui est tout autre chose.</p>

<h2>Pourquoi la correction paraît démesurée</h2>

<p>Les travaux de Hersh Shefrin sur l’affect et la prise de décision financière décrivent comment les investisseurs substituent un sentiment d’aisance à une véritable évaluation de la probabilité pendant les périodes calmes. Lorsque le mouvement des prix confirme ce sentiment, celui-ci se trouve renforcé. Trois semaines de progression graduelle de l’or, alimentées par les flux liés au « trade de dévaluation », ont bâti exactement ce type de confort affectif, un confort sans lien avec le risque de transport dans le détroit d’Ormuz, mais qui se trouvait juste à côté sur le même graphique.</p>

<p>C’est pourquoi la baisse causée par Warsh vendredi et les frappes de l’île de Larak en fin de semaine se traduisent par un choc composé plutôt que par deux événements distincts et explicables. Le portefeuille n’intégrait activement aucun des deux risques dans son prix. Il intégrait plutôt leur absence, et cette absence a pris fin en une seule fin de semaine.</p>

