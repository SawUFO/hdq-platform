<h2>Pourquoi un écart de taux qui se resserre est un signal plus important pour le 2 septembre que la prime du détroit d’Ormuz</h2>

<p>Le cadrage du 2 septembre ce mois-ci s’est concentré sur l’inflation importée liée à l’énergie, découlant de l’impasse au détroit d’Ormuz. Ce cadrage tient toujours, mais un second signal, concurrent, est apparu cette semaine et pointe dans la direction opposée. L’obligation du gouvernement du Canada à 10 ans se situe près de 3,68&nbsp;%, tout juste sous le sommet de deux mois de 3,72&nbsp;% atteint le 10 août, ce qui ressemble à une confirmation du scénario d’inflation importée. Sauf que le dollar canadien s’est raffermi pendant la même période, clôturant à 1,3764&nbsp;$&nbsp;US vendredi, alors même que les rendements américains à long terme ont grimpé à un sommet de 19 ans et que l’or s’est envolé. Une hausse des rendements mondiaux accompagnée d’un dollar canadien plus fort ne correspond pas à une crainte inflationniste propre au Canada. Cela correspond à un problème de crédibilité propre aux États-Unis, dont le huard profite, pour l’instant, du bon côté.</p>

<p>Cette distinction compte pour ce que Macklem soupèse en vue du 2 septembre. Si une partie de la pression sur les rendements ce mois-ci relève de la situation budgétaire de Washington plutôt que de la demande canadienne, le canal d’inflation importée contre lequel il doit se prémunir est plus faible que ne le laisse croire le seul rendement de l’obligation du gouvernement du Canada. Cela n’efface pas la prime du détroit d’Ormuz logée dans le WTI. Cela signifie que les deux forces ne tirent plus dans la même direction, et qu’une décision de taux fondée uniquement sur le canal énergétique ne lirait que la moitié du signal.</p>

