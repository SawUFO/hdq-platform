<p>Le canal de transmission n’était pas les bénéfices. C’était le prix de l’argent. Un baril à 116,72&nbsp;$&nbsp;US fait augmenter les revenus des producteurs canadiens, mais ce même baril a accru les probabilités que la Banque du Canada resserre sa politique monétaire malgré un marché du travail en repli, et un taux directeur plus élevé pèse sur les valorisations de l’ensemble de l’indice. Les deux effets étaient à l’œuvre cette semaine, et l’évolution des cours concorde avec la prédominance du second.</p>
<h2>Une hausse intégrée aux prix malgré une inflation faible</h2>
<p>Selon des données de Bloomberg rapportées par Canadian Mortgage Trends, la tarification des swaps pour une hausse de la Banque du Canada le 28 octobre est passée d’environ 35&nbsp;% le 16 octobre à environ 80&nbsp;% le 19 octobre. BMO, RBC Dominion Securities et Desjardins prévoient depuis un relèvement du taux de 2,25&nbsp;% à 2,50&nbsp;%. Les estimations varient selon la source, d’environ 54&nbsp;% à 87&nbsp;%.</p>
<p>Le réajustement est survenu le lundi même où Statistique Canada a fait état d’un IPC-tronq de septembre à 1,8&nbsp;%, sous le consensus de 1,9&nbsp;% et sous la cible de 2&nbsp;%, l’IPC-méd s’établissant à 1,9&nbsp;%. L’IPC global a atteint 3,1&nbsp;%, l’essence ayant augmenté de 27,8&nbsp;% en glissement annuel. Le Canada a aussi perdu 68&nbsp;000 emplois en septembre, deuxième baisse mensuelle consécutive.</p>
<p>Dans un discours prononcé le mois dernier, le gouverneur Tiff Macklem a affirmé que la Banque peut faire abstraction de l’effet direct de la hausse des prix du pétrole tant que les pressions restent contenues, selon InvestingLive. Une hausse intégrée à près de 80&nbsp;% laisse donc entendre que le marché s’attend à ce que la Banque juge ces pressions désormais non contenues, alors même que l’inflation fondamentale reste sous la cible.</p>
<p>Le rendement canadien à 2 ans a enregistré le mouvement, grimpant de 12 points de base le 19 octobre, de 3,21&nbsp;% à 3,33&nbsp;%, avant d’en effacer l’essentiel d’ici le 22 octobre. Il a terminé la période à 3,22&nbsp;%, un point de base au-dessus de son niveau du 16 octobre.</p>
