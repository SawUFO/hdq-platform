<h2>Le mouvement qui aurait dû se renverser ne l’a pas fait</h2>

<p>L’or n’a pas rendu ses gains lorsque les rendements se sont renversés. Il les a maintenus jusqu’à jeudi, a grimpé vendredi pour une avance hebdomadaire proche de 5&nbsp;%, et a ajouté 1&nbsp;% de plus lundi pour atteindre son plus haut niveau depuis la mi-mai. Trois séances et demie après la disparition du mécanisme des taux qui justifiait le mouvement initial, l’évolution des prix qu’il a produite n’est pas seulement intacte, elle continue de croître.</p>

