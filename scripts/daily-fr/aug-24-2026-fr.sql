<h2>Confirmation, pas réévaluation</h2>

<p>Les travaux de Daniel Kahneman et Amos Tversky sur l’ancrage décrivent un schéma apparenté à l’échelle individuelle&nbsp;: une fois un point de référence fixé, la nouvelle information est soupesée par rapport à cet ancrage plutôt qu’évaluée sur ses propres mérites. Un investisseur ancré le 19 août à l’idée que «&nbsp;l’or grimpe parce que Washington ne maîtrise plus ses coûts d’emprunt&nbsp;» n’a pas besoin que le renversement des rendements soit perçu comme une infirmation. L’ancrage survit parce que rien ne force une comparaison avec l’affirmation d’origine.</p>

<p>La distinction compte pour la suite. Un prix qui suit encore son moteur se corrige quand celui-ci se renverse. Un prix qui suit un récit à propos de son moteur peut continuer de grimper sur des éléments sans lien avec l’affirmation d’origine, jusqu’à ce que quelque chose force les deux à se reconnecter, généralement de façon brusque. Les achats des banques centrales et un dollar américain plus faible sont des appuis structurels réels sous le mouvement de l’or cette année. Le segment précis du mercredi au lundi n’en fait pas manifestement partie.</p>

