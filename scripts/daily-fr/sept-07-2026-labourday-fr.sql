  '<p>La fête du Travail au Canada n’a pas commencé comme une célébration. Elle a commencé comme une grève qui a échoué.</p>
<p>En avril 1872, des imprimeurs de Toronto ont cessé le travail pour réclamer une journée de neuf heures, alors que la norme était de douze heures par jour, six jours par semaine. Leurs employeurs les ont fait arrêter en vertu de lois sur le complot qui traitaient l’organisation syndicale comme un acte criminel. La grève n’a pas obtenu la journée de neuf heures. Mais le spectacle de dirigeants syndicaux menottés a fait basculer l’opinion publique, et le gouvernement du premier ministre John A. Macdonald y a vu une occasion. En quelques mois, le Parlement a adopté la Loi sur les syndicats ouvriers de 1872, légalisant l’activité syndicale dans tout le pays. Une grève perdue avait produit un droit protégé.</p>
<h2>Vingt-deux ans entre le défilé et la loi</h2>
<p>Ce qui a suivi n’a pas été une victoire unique, mais une lente construction institutionnelle. Les travailleurs de Toronto et d’Ottawa ont tenu des défilés annuels tout au long des années 1870 et 1880 pour souligner le Mouvement des neuf heures. Un défilé tenu à Toronto en juillet 1882 était si imposant qu’un dirigeant syndical américain témoin de l’événement, Peter J. McGuire, est rentré chez lui organiser un défilé semblable à New York en septembre de la même année, un événement aujourd’hui reconnu comme la première fête du Travail américaine.</p>
<p>La reconnaissance fédérale canadienne n’est venue qu’en 1894. Une commission royale l’avait recommandée dès 1889. Les pressions syndicales l’ont fait adopter par le Parlement sous le premier ministre John Sparrow David Thompson, et la sanction royale est survenue en juillet, fixant la fête du Travail au premier lundi de septembre. Les États-Unis ont suivi la même année sous la présidence de Grover Cleveland.</p>
<h2>Ce que montrent réellement les heures travaillées</h2>
