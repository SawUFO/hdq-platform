<p>Aucune loi unique du Parlement n’a produit cette courbe. Elle résulte de l’effet cumulé du Mouvement des neuf heures, d’un mouvement des huit heures survenu des décennies plus tard, de la négociation collective, des lois sur les normes du travail et de l’évolution de la structure économique, chaque facteur abaissant un peu plus la ligne et consolidant l’acquis une fois obtenu.</p>
