<p>Le WTI a clôturé à 86,30&nbsp;$ vendredi et le Brent à 93,40&nbsp;$, tous deux en hausse sur la semaine pour une deuxième avance hebdomadaire consécutive, mais pour une raison sans lien avec le mouvement de l’or. Les États-Unis préparent de vastes nouvelles sanctions économiques contre l’Iran, et les espoirs d’une réouverture à court terme du détroit d’Ormuz se sont affaiblis au cours de la semaine.</p>

