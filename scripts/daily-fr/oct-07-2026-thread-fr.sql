<p>Trois dates comptent désormais le plus. L’Enquête sur la population active paraît le 9 octobre à 8&nbsp;h&nbsp;30, après un taux de chômage de 6,4&nbsp;% en août et une perte de 41&nbsp;700 emplois. L’IPC suit le 19 octobre, l’inflation globale s’établissant à 3,0&nbsp;% et l’IPC-tronq. à 1,9&nbsp;%. La décision de la Banque du Canada et le Rapport sur la politique monétaire arrivent le 28 octobre à 9&nbsp;h&nbsp;45, le même jour que la Fed à 14&nbsp;h, où les opérateurs voyaient environ 17&nbsp;% de chances d’une hausse en octobre mercredi.</p>
