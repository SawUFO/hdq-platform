<h2>Confirmation, pas réévaluation</h2>

<p>Les travaux de Daniel Kahneman et Amos Tversky sur l’ancrage décrivent un schéma apparenté à l’échelle individuelle : une fois qu’un point de référence est fixé, toute nouvelle information est pesée par rapport à cet ancrage plutôt qu’évaluée pour elle-même. Un investisseur ancré, depuis le 19 août, à l’idée que « l’or grimpe parce que Washington ne parvient pas à maîtriser ses coûts d’emprunt » n’a pas besoin que le renversement des taux soit perçu comme infirmant cette thèse. L’ancrage survit parce que rien ne force une comparaison avec l’affirmation d’origine.</p>

