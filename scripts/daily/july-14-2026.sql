<h2>A Shock That Only Found One Door</h2>

<p>This is not what a full risk repricing looks like. When the conflict first erupted in late February, the reaction ran wide: equities sold off, volatility spiked, and currencies tied to broader risk sentiment moved together. Tuesday''s version ran narrow. Oil and industrial metals absorbed the news. Everything priced on a broader risk premise, equities, sovereign debt, the loonie, treated it as background.</p>

