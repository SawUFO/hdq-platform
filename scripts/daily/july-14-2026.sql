<h2>How the Structure Actually Works</h2>

<p>A prescribed-rate loan is a non-registered strategy, distinct from RRSP or TFSA contribution planning. A higher-income spouse or parent lends funds directly to a lower-income spouse, common-law partner or family trust, charging interest at no less than the prescribed rate in effect when the loan is made. The borrower invests the funds and reports the investment income and capital gains in their own hands, taxed at their lower marginal rate. The borrower then pays the lender interest at the loan''s locked rate, and the lender reports that interest as income.</p>

<p>The strategy works when the after-tax return the borrower earns on the invested funds exceeds the 3 percent carrying cost. At the current rate, that bar is lower than it has been in years outside the past five quarters. The prescribed rate hit 6 percent in the first half of 2024 before easing to 4 percent through the first half of 2025, then to 3 percent starting in the third quarter of 2025, where it has stayed since.</p>

