<h2>What the Bond Market Heard on Saturday</h2>
<p>The sequence matters. On Saturday, October 17, Governor Tiff Macklem spoke to reporters in Bangkok after the annual International Monetary Fund meetings. The Globe and Mail reported that his remarks suggested high oil prices were becoming a major concern for the Bank of Canada. Scotiabank Economics noted that pricing for an October hike roughly doubled by Monday morning, from about 9 basis points on Friday to about 18 basis points.</p>
