<h2>Availability and Anchoring Do the Work</h2>
<p>Amos Tversky and Daniel Kahneman described the availability heuristic in 1973: people judge how likely an outcome is by how easily an example comes to mind. A central bank governor speaking on a Saturday is easy to recall. A CPI-trim reading 0.1 percentage point below consensus is not.</p>
<p>The same two researchers documented anchoring in 1974. Once a market holds a number in mind, such as 18 basis points of hike pricing, later information tends to be judged against that number rather than on its own merits. The core readings arrived into a market that already had a new reference point.</p>
<p>None of this means the repricing was wrong. A governor who flags oil as a concern is giving real information about how the committee may weigh a 27.8% gasoline increase. The behavioural question is proportion: whether one speech should move pricing as much as the inflation data the Bank of Canada itself targets.</p>
<h2>The Jobs Rally Ran on the Same Engine</h2>
