<p>Manufacturing lost 13,000 positions in the first full month after a new round of US tariffs took effect against Canada. That detail drew far less attention than the repricing it accompanied, which fits the same pattern.</p>
<p>Prospect theory, introduced by Kahneman and Tversky in 1979, holds that people do not weigh probabilities in a straight line. A 15-point swing in hike odds is therefore not experienced as 15 points, and the emotional weight of each swing can exceed its arithmetic.</p>
