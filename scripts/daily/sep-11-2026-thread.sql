<h2>Ottawa and Washington Just Reached the Same Answer From Different Directions</h2>
<p>The Federal Reserve meets September 16, and the core CPI number released Friday gives officials the cleanest case yet for a hike: a fifth of the CPI basket showed a monthly increase, energy is up 16.3 per cent year over year, and the Cleveland Fed nowcast now pegs September core CPI at an annualized pace above 2.4 per cent. None of that is about tariffs on Canadian goods. It is entirely a Hormuz story arriving through the gas pump.</p>
<p>Bank of Canada Governor Tiff Macklem is looking at a different mechanism producing the identical conclusion. Retaliatory tariffs from Canada, covering $20 billion of American goods at rates from 15 to 50 per cent, took effect this month and are now showing up as a second, domestic inflation channel layered on top of the imported oil shock. The Government of Canada 10-year yield closed the week at 3.94 per cent, a two-year high, as investors demanded a larger risk premium for holding Canadian duration into that outlook. Macklem has already said the bank is prepared to raise rates if inflation stays elevated. That is the same sentence Fed officials are building toward, for a partly overlapping and partly separate reason.</p>
<p>This yield climb tracks directly against the date Canadian tariffs took effect, and the acceleration after that date is the part worth sitting with.</p>
