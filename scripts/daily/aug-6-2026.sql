<h2>The Rate Locks In. The Payment Deadline Does Not</h2>

<p>Once a prescribed rate loan is established, the rate applying to that loan is fixed for its entire term, regardless of where the prescribed rate moves in future quarters. A loan made this quarter at 3% stays at 3% even if the rate climbs to 5% by 2028. That permanence is the main appeal of the strategy and the reason advisors have been recommending origination during the six quarter run at 3%.</p>

<p>The part of the strategy that does not take care of itself is the annual interest payment. The borrowing family member must pay interest to the lender by January 30 of the following year, calculated at the rate locked in when the loan began. Miss that date and the CRA''s attribution rules apply retroactively: investment income earned on the loaned funds is attributed back to the lender for the year the payment was missed and for every year after, unwinding the income split permanently, not just for the year in question.</p>

