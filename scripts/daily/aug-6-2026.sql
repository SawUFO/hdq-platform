<h2>The Growth Rate Barely Moved. The Story Around It Did</h2>

<p>Both quarters delivered essentially identical top line growth. Both beat estimates. Both showed accelerating merchant adoption of Shopify''s AI tools. The mechanism that separated a 16% decline from a 17% advance was not in the revenue line. In May, management''s guidance pointed to sharply higher operating expenses tied to AI infrastructure spending, and the market read that as evidence Shopify''s margins would compress under AI-driven cost pressure.</p>

<p>By August, the same category of spending produced the opposite read. Jefferies, BofA and RBC framed Shopify''s checkout, payments and platform economics as structurally advantaged in an AI-native commerce environment, and multiple banks, including BofA, Truist and Jefferies, raised price targets to the $175 to $180 range within hours of the print. The underlying capital allocation had not changed direction. The narrative describing it had.</p>

<h2>Kahneman and Tversky''s Representativeness at Work</h2>

<p>Kahneman and Tversky''s 1974 work on judgment under uncertainty described representativeness: people assess new information by how well it fits an already-active mental pattern, not by independently weighing what the evidence should change. In May, the active pattern was "AI disruption threatens software margins," reinforced by a Rothschild and Co Redburn downgrade in July that cited Meta''s small business AI tools as a competitive threat to Shopify. Rising costs slotted neatly into that pattern and were punished.</p>

<p>By August, the active pattern had flipped to "AI is expanding the merchant funnel, not replacing it." Shopify disclosed that AI-driven traffic through its Sidekick tool had nearly quadrupled year over year. The same category of cost, once read as margin risk, was now read as evidence of demand generation. The financial substance connecting the two quarters was closer than the market''s verdict on either day suggested.</p>

