<h2>One Phrase Dropped, One Finding Published</h2>

<p>Wednesday, the Fed raised its target range by 25 basis points to 3.75 to 4.00 percent, its first hike since July 2023. Strategists flagged a specific change in the accompanying statement: the language that had previously attributed firm inflation to a supply shock tied to energy prices was gone. The September statement called current price growth simply elevated. That is not a wording accident. Calling something a supply shock implies it passes. Calling it elevated implies it does not, on its own, resolve.</p>

<p>The same day, the Bank of Canada released the minutes from its own September 2 decision to hold at 2.25 percent. Governing Council members had looked at the identical driver, gasoline prices pushed higher by the conflict touching Iran, and reached a narrower finding: little evidence that elevated energy prices were passing through broadly to other goods and services in Canada. The council said it would act with multiple hikes if that pass-through appeared. It has not appeared yet, in its own reading.</p>

<p>Two central banks, one energy shock, and a same-day split on how to name it. The Fed treated the shock as durable enough to justify moving. The Bank of Canada treated it as still contained enough to justify waiting for evidence that has not shown up in the data it reviewed three days earlier.</p>

<h2>The Shock Itself Started Reversing By Morning</h2>

<p>Brent crude fell 1.69 percent Thursday to 104.04 US dollars, and West Texas Intermediate slipped roughly 1.06 percent to about 101.34, as additional Saudi crude routed through Oman and a faster prospective repair of Saudi export infrastructure eased the supply fear that had driven both benchmarks toward four-month highs earlier in the week. The retreat is the second straight session of easing, not a single-day wobble.</p>

