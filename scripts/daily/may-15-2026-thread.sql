<h2>The TSX Base Metals Selloff Was a Rate Story, Not a Copper Demand Story</h2>

<p>The morning''s Market desk identified base metals as the TSX sector leading today''s decline. By the close, that was confirmed: the TSX shed approximately 398 points to close near 33,870, with copper-exposed names falling more than 4% on the session. The instinct is to read this as a demand signal. The more accurate read is that it was a rate repricing first.</p>

<p>J.P. Morgan''s base and precious metals team calculates that every US$10/bbl oil shock strips approximately 1.4 percentage points from copper demand growth forecasts by dampening global GDP. That mechanism takes quarters to transmit. What happened today was faster: the base metals sector, which trades on global growth expectations, sold off because the market concluded that the new Fed chair inherits an environment where the next FOMC move might be a hike. Growth-sensitive commodities re-rate immediately when the rate path moves.</p>

<p>The Bank of Canada cannot treat this as an American problem. Governor Macklem''s June 3 decision is now materially more complicated than it was at 10:00 AM this morning. The BoC had been managing a narrow path: hold rates while inflation remains above target, but signal eventual cuts as the economy softens. That path depends on the U.S. rate path remaining roughly neutral. If Warsh''s first FOMC meeting on June 16 to 17 signals a hawkish pivot, the five-year Government of Canada bond yield will move, fixed mortgage rates will follow, and the BoC will be forced to respond to a transmission it did not initiate.</p>

