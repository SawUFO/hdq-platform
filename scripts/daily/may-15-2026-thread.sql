<h2>The Safe Haven Trade Inverted Today, and That Is the Warsh Signal</h2>

<p>Kevin Warsh became Federal Reserve chair at midnight as Jerome Powell''s term expired. He inherits a central bank where the FOMC''s April meeting already had three members signalling that the next move could be a rate hike rather than a cut. He arrives with U.S. CPI at 3.8%, U.S. producer prices up 6.0% in April, and WTI crude at $103.50 after the Trump-Xi summit in Beijing closed without any meaningful progress on the Strait of Hormuz blockade.</p>

<p>The bond market''s reaction to the Warsh transition and the summit''s failure to produce Hormuz progress arrived simultaneously this afternoon. The 10-year U.S. Treasury yield spiked 11 basis points to 4.57%, its highest level in a year. The 30-year hit 5.12%, a level not seen since June 2007. Gold, which is a non-yielding asset, fell when real yields rose sharply. This is textbook: when investors conclude that rates are going higher rather than lower, the opportunity cost of holding gold increases and the metal sells off.</p>

