<h2>What July 15 Now Requires</h2>

<p>The Bank of Canada''s next scheduled decision is July 15, which also carries the Monetary Policy Report. The MPR is the Bank''s first full update to its official growth and inflation projections since April. It was already going to be the most consequential communication of the year. Friday''s oil move makes it more so.</p>

<p>If a Hormuz agreement is signed over the weekend, as Trump suggested it might be, the BoC will have three weeks before July 15 to assess whether the energy premium is genuinely unwinding or whether the first ceasefire will hold more durably than the April 8 version did. The April ceasefire also produced a WTI selloff, from above $106 to $83.85 in a single session. It did not hold. WTI climbed back above $100 within two weeks.</p>

<p>That precedent is the reason the bond market''s move on Friday is measured, not decisive. The GoC 5-year yield did not fall 30 basis points. It eased 9. Swap markets did not reprice the BoC path to cuts. They went quiet. The market is not pricing resolution. It is pricing uncertainty about whether this particular round of deal news is structurally different from April''s. The honest answer, as of Friday close, is that nobody knows.</p>

<p>What the BoC knows is that its June 10 statement was written for a world that may or may not exist by July 15. The "looking through" framing for energy inflation assumed the shock would persist long enough to require monitoring. If WTI is at $75 by mid-July, that framing requires explicit revision. Governor Macklem said on June 10 that the next move could go either way. That was true then. It is more urgently true now, and in a different direction than the hawkish lean of the statement implied.</p>

<p>The mortgage renewal cohort renewing in October through December, the largest wave of the cycle, will be repricing into whatever rate environment July 15 produces. A BoC that enters July 15 with its June 10 language intact, despite oil having fallen 15% from its war-era highs, would be leaving a misleading signal in the market at the worst possible moment for borrowers trying to decide between fixed and variable.</p>

