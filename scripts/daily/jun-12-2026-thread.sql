<h2>What the Bond Market Saw That Macklem Did Not</h2>

<p>The Bank of Canada''s June 10 hold statement was careful, deliberate, and already outdated. The Bank said it was "looking through" the war''s near-term impact on inflation, citing "limited evidence of broad-based pass-through from energy costs to other consumer prices." CPI at 2.8% in April was flagged as driven by energy; core had moved down to 2.1%. The language positioned the Hormuz premium as a temporary distortion, not a persistent structural shift.</p>

<p>That framing requires the energy shock to remain. If WTI normalizes from $85 back toward the $65-to-$70 range it occupied before the war, the BoC''s inflation arithmetic changes completely. The 2.8% headline reading that anchored the June 10 statement dissolves. Energy''s contribution to CPI reverses from a source of upside pressure to a disinflationary tailwind. The Bank that spent June 10 signaling vigilance against inflation suddenly faces a very different calculation: a technical recession in Q1 2026, a consumer still fragile from three years of elevated rates, and an energy sector repricing lower into the renewal wave.</p>

<p>The GoC 5-year yield felt this before the press conference ended. It eased 9 basis points on Thursday and continued lower Friday, falling from 3.15% earlier in the week toward 3.0%. That move is not large in isolation. In context it matters: the yield had been tracking above 3.0% for most of May and early June, keeping 5-year fixed mortgage rates firm around 4.9% to 5.0% at the Big 6 banks. A sustained move to 3.0% or below begins to soften those rates. The 2026 mortgage renewal wave, which HDQ has tracked all year as the transmission mechanism connecting BoC policy to household balance sheets, becomes less punishing if yields drop 30 to 40 basis points before the October-to-December renewal peak.</p>

<p>WTI''s daily price range and the 5-year bond yield are not obviously linked. Today they are.</p>

<h2>The TSX''s Sector Rotation Is the Most Honest Signal in the Room</h2>

<p>The TSX''s split today is not noise. When oil falls on deal-proximity signals rather than demand destruction, the market''s assessment of what changes runs through two channels: energy producers lose the premium, and rate-sensitive sectors recover it.</p>

<p>Friday''s pattern confirmed both. The TSX energy sub-index fell approximately 1.8% as WTI retreated, with Canadian Natural Resources, Suncor, and Cenovus all lower. These names had been the compositional anchor of the TSX''s year-to-date outperformance, up more than 9% against a flat-to-down S&P 500. A sustained oil correction unwinds that relative trade and pulls the broad index lower even as its non-energy components stabilize.</p>

<p>The financials held. Rate-sensitive sectors, particularly utilities and real estate investment trusts, caught a bid as the yield move filtered through. This is the market pricing a scenario the Bank of Canada has not yet described: a BoC that moves toward easing posture faster than the June 10 statement implied, not because of economic weakness alone but because the inflation rationale for the hawkish lean evaporates with the oil premium.</p>

<p>The TSX sector rotation today is a forecast. It says the market believes the oil-driven inflation chapter is closer to its end than the Bank of Canada''s official language suggests.</p>

