<h2>The Purity Threshold That Decides Registered-Account Eligibility</h2>

<p>Physical gold bars, wafers, and coins are a qualified investment for an RRSP, RRIF, TFSA, FHSA, RESP, and RDSP, provided the metal meets a minimum purity of 99.5% and is held in a form consistent with recognized exchange trading standards. Silver has to meet a 99.9% purity threshold. This has been the rule since the 2014 federal budget expanded qualified investments beyond gold certificates to the metal itself.</p>

<p>The condition that trips up clients is custody. The plan''s trustee has to hold the bullion, typically through an insured vault arrangement at a bank or brokerage. A client cannot buy eligible bullion, register it inside an RRSP or TFSA, and then take the coins home. In practice, few retail platforms operationally support registered-account physical bullion at all, which is the main reason this eligibility rule matters less in daily practice than the next one.</p>

<h2>Personal Possession Breaks the Shelter</h2>

<p>Gold a client holds themselves, in a safety deposit box or a home safe, is not inside any registered structure and gets no sheltering whatsoever. On sale, the gain is a capital gain like any other capital property, with 50% of the gain included in taxable income at the client''s marginal rate. There is no principal residence style exemption and, for investment grade bullion bought and held for appreciation, no personal-use property exemption either.</p>

