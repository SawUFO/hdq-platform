<h2>The Availability Heuristic Runs on What Is Easy to Recall</h2>

<p>Amos Tversky and Daniel Kahneman''s 1973 work on the availability heuristic showed that people estimate the probability of an event by how easily examples come to mind, not by the underlying base rate. A week of falling oil prices, a Fed hold, and a VIX that dropped 17.28% Thursday to close at 17.09 are all recent, vivid, and easy to recall. A stalled negotiation over who controls tolls on a shipping lane is none of those things.</p>

<p>The negotiation is the part that has not moved. Iran''s Deputy Foreign Minister Kazem Gharibabadi said on July 29 that Oman''s proposal for joint oversight of the Strait of Hormuz had not addressed Tehran''s concerns about control of the waterway, and Iran countered with a plan that keeps more authority in its own hands. That exchange happened two days before Friday''s price moves. It has not been resolved. It has been talked past.</p>

<h2>Operational Improvement Is Not the Same as a Deal</h2>

<p>The case for optimism is real, and the Market Desk has been tracking it. Kpler data showed 14 commodity vessels transited the Strait of Hormuz in both directions on Wednesday, up from single digit daily crossings the week before. Qatar dispatched its first LNG cargo through the strait since the disruption began. These are genuine signs that shippers are finding a way through a conflict that has not ended.</p>

<p>Oil is pricing the traffic data. Gold is pricing the fact that Tehran and Muscat are still exchanging competing proposals over who runs the checkpoint. Both readings are defensible on their own terms. The problem is not that one commodity is wrong. It is that an investor who only follows one of them will walk away with a false sense of how settled this is.</p>

<h2>Why the Last Five Months Make This Worse, Not Better</h2>

<p>This is not the first quiet stretch since the Strait of Hormuz crisis began February 28. There have been ceasefires, stand downs, and multi day pauses before, and several have reversed. A client whose mental model is built from the last two weeks of headlines has a thinner sample than a client who remembers the full five month pattern of de-escalation followed by renewed strikes.</p>

<p>Shlomo Shefrin''s research on framing effects adds a second layer: how a scenario is described changes the risk investors assign to it, independent of the facts. "Pause in strikes" reads as closer to resolution than "sovereignty dispute unresolved," even when both describe the same Tuesday.</p>

