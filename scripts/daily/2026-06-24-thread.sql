<h2>The Channel That Calmed Bonds Is the One the Tax Desk Built a Window On</h2>

<p>This morning''s Tax and Wealth desk piece flagged the CRA holding its prescribed interest rate at 3 percent for a fifth straight quarter while Government of Canada and US Treasury yields had climbed this year on energy driven inflation. That gap is the entire case for setting up an income splitting loan before the next quarterly reset. A wider gap between the prescribed rate and market yields means more income shifted at the lower rate.</p>

<p>Wednesday showed the same mechanism running in reverse. The US 10 year Treasury yield eased toward 4.3 percent as oil slid, with CNBC reporting explicitly that Treasury yields fell because oil prices fell. Canadian yields move in close correlation with Treasury yields through the same cross border transmission channel the Economy desk described this morning. Nothing about today closes the planning window. But today is the clearest evidence yet of exactly what would close it: a continuing energy de-escalation that pulls bond yields back down toward the prescribed rate rather than away from it.</p>

<h2>CAD Is the One Asset Not Getting the Relief</h2>

<p>Gold settled near $3,987 an ounce on Wednesday, its first close below $4,000 since November 18, 2025, down more than 12 percent over the past month. Oil fell hard too. By the logic of a fading war premium, a calmer Canadian dollar should follow both of those declines. It did not. The Canadian dollar weakened to 70.24 cents US, a fresh high for the US dollar against the loonie this year.</p>

<p>Two separate forces are doing this, and they are worth keeping apart for client conversations. Falling oil hurts CAD directly through Canada''s terms of trade, a mechanical drag that has nothing to do with sentiment. Separately, and faster, markets now price a 68 percent chance of a Federal Reserve hike in September, up from 29 percent a week ago. That repricing follows the Fed''s own upgraded inflation forecast, a median 2026 PCE estimate of 3.6 percent versus 2.7 percent in March, delivered even as energy prices fall. This morning''s Economy desk framed the Bank of Canada and Fed divergence as a function of the war''s inflation effects. Wednesday''s data points to a driver sitting outside the war entirely, one that will not close just because the Strait does. Thursday''s 8:30 am ET data slate, including PCE and GDP, is the next test of that ex energy inflation story, and a quiet detail from the API and EIA reports, Cushing inventories dipping toward critical operating minimums even as prices collapse, is a reminder that today''s de-escalation trade has very little physical cushion behind it if the diplomacy stalls.</p>

