<h2>Eighteen Weeks of Correlation, Broken in Two Sessions</h2>

<p>From early April through late June, the relationship held. WTI drifted from the low $90s toward the high $80s through May, and USD/CAD firmed and eased in step. When the oil collapse accelerated in June, from $84.60 in the second week to $70.90 by June 26, the loonie weakened alongside it, with USD/CAD rising from 1.3820 to 1.4202 over the same stretch. Every advisor who has fielded a client question about the dollar this spring has been giving some version of the same answer: it is the oil price.</p>

<p>The final week broke the pattern. WTI fell another 2.99 percent, from $70.90 to $68.78. USD/CAD did not follow. It eased instead, a genuine decorrelation rather than a pause in the existing trend.</p>

<h2>Why the NFP Miss Did What Oil Could Not</h2>

<p>The June nonfarm payrolls report, released Thursday, showed 57,000 jobs added against a 110,000 consensus, the weakest print in four months. Fed funds futures priced the probability of a September hike down to roughly 50 percent, from 66 to 67 percent before the release. Fed Chair Kevin Warsh had already signaled earlier in the week that inflation expectations were moderating, and the payrolls miss reinforced the case for the central bank to stay patient.</p>

<p>That combination pushed the US dollar broadly lower, not just against the loonie. Gold caught the same current, trading near $4,174 on July 4, its firmest level in about a month, after touching an eight-month low earlier in the week. The mechanism for CAD strength this week was not a Canadian story at all. It was a US rate-path story that happened to lift the loonie as a side effect of broad dollar weakness, the same force that lifted gold.</p>

<h2>The TSX''s Own Signal: Gold Miners, Not Energy, at the Wheel</h2>

<p>The TSX composite closed at 35,274.84 on July 3, up 0.88 percent on the session and just 355 points below its 52-week closing high of 35,629.90. Through most of the Hormuz disruption, energy names did the heavy lifting for the index. This week, the leadership rotated. The TSX capped energy index rose 0.62 percent on July 3, while gold miners drove the broader gain as bullion prices firmed on the same rate-repricing story working through the currency.</p>

<p>The index is not making a new high on the strength of the story that got it this far. It is making a run at one on a different story entirely, which matters for how an advisor frames Canadian equity exposure heading into the back half of the year.</p>

