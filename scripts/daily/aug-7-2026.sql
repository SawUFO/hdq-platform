<h2>The Availability Heuristic Has a Textbook Case Running in Real Time</h2>
<p>Amos Tversky and Daniel Kahneman described the availability heuristic in 1973: people judge the probability of an event by how easily examples come to mind, not by its actual base rate. A headline that is vivid, recent, and easy to recall gets weighted far more heavily than the slower, harder to picture process of a war actually ending.</p>
<p>The three session slide into August 5 is the heuristic in action. A reported agreement between two governments, still under review by Iran''s parliament and still requiring the sign off of an Acting Supreme Leader who has been in hiding since February and whose communication channels are, by his own president''s description, difficult, was priced as though the resolution were close to final. The draft terms reported this week would bar US and Israeli linked vessels and impose fees of up to seven percent of cargo value, conditions a former State Department official called unlikely to be acceptable in Washington. None of that complexity showed up in the price move. The headline that a deal was advancing did.</p>
