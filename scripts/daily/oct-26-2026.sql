<h2>The Availability Heuristic Does the Arithmetic</h2>
<p>Amos Tversky and Daniel Kahneman described the availability heuristic in 1973: people judge how common or how likely something is by how easily examples come to mind. A gasoline price is posted on a sign, changes visibly from week to week, and is paid in a single transaction. Rent, insurance premiums and restaurant prices arrive on different calendars.</p>
<p>Olivier Coibion and Yuriy Gorodnichenko made the macroeconomic version of the argument in a 2015 paper, finding that household inflation forecasts have tracked oil and gasoline prices closely and attributing that to the high visibility of gasoline.</p>
<p>The size of the effect is contested. Lutz Kilian and Xiaoqing Zhou of the Federal Reserve Bank of Dallas estimated, in a 2022 paper in the Journal of Applied Econometrics, that gasoline price shocks account for 39% of the variation in household inflation expectations since 1981. That is a large share, and it is also well short of all of it.</p>
<h2>The Asymmetry Is the Costly Part</h2>
<p>The Federal Reserve Bank of San Francisco made the mechanism more specific in an Economic Letter published on August 31, 2026. Using household survey responses, the letter found that inflation expectations rise when households expect gasoline prices to climb, and that the response is much stronger when expected gas price growth increases than when it decreases.</p>
<p>The letter added that expectations may not retrace those increases when households later expect the run-up in gas prices to unwind. That ratchet is consistent with the loss aversion Kahneman and Tversky documented in 1979, in which a loss weighs more heavily than a gain of the same size. A household that has absorbed a 27.8% increase at the pump registers further increases as fresh losses and treats declines as a partial recovery of something already taken.</p>
