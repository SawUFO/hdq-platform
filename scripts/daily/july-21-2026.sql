<h2>Why a Stable Rate Is More Valuable Than a Low One</h2>

<p>A prescribed rate loan lets a higher income spouse or family member lend money to a lower income spouse, adult child, or family trust at the prescribed rate in effect when the loan is advanced. The borrower invests the funds and pays tax on the investment income at their own, lower marginal rate. The rate locks in for the life of the loan. It does not reset when the CRA''s quarterly rate moves.</p>

