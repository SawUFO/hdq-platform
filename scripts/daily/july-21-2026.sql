<h2>The Anchor Investors Cannot Let Go Of</h2>

<p>Amos Tversky and Daniel Kahneman''s 1974 work on anchoring showed that people form judgments by starting from an initial reference point and adjusting insufficiently away from it. For gold investors in 2026, that anchor is January''s record high of $5,608.35, set in the opening days of the conflict when the metal gained sharply on the initial shock of the US and Israeli strikes on Iran.</p>

<p>Every subsequent price move gets evaluated against that anchor rather than against the conditions that actually determine gold''s price today. The result is a persistent expectation gap: clients see ten nights of strikes and expect ten nights of gains, because the anchor from February taught them that escalation and gold prices move together. They do not, reliably, and the gap between expectation and outcome is where the client conversation gets difficult.</p>

<h2>Why the Mechanism Has Actually Reversed</h2>

<p>Gold''s post February rally was a shock response to a surprise attack. The current phase of the conflict is a known, ongoing state, and the market has priced it as such. What has changed since is the monetary policy channel. Cleveland Fed President Beth Hammack was the latest official to warn that further rate hikes may be needed to contain inflation, and futures markets now assign an 80% probability to a December hike, up from 73% a week earlier.</p>

<p>Higher rate expectations raise the opportunity cost of holding a non yielding asset like gold, and that pressure has been strong enough to offset the safe haven bid from an active war. Elevated oil prices are doing double duty here: they support the geopolitical risk premium in gold while simultaneously feeding the inflation expectations that make higher rates more likely, which works against gold. The two forces have largely cancelled out, leaving the metal range bound between roughly $3,965 and $4,190 for the past month.</p>

<h2>The Disposition Effect Is the Live Risk Now</h2>

<p>Hersh Shefrin and Meir Statman''s research on the disposition effect describes investors'' tendency to hold losing positions too long while selling winners too early, driven by a reluctance to realise a loss and crystallise the original decision as a mistake. A client who added to gold near the January peak is now sitting on a meaningful unrealised loss on that tranche, even as headlines suggest the case for holding gold has never been stronger.</p>

<p>That combination is exactly the setup the disposition effect predicts will produce the longest holding periods. The narrative and the position reinforce each other: the war continues, so the client keeps the trade on, waiting for the price action to eventually justify the thesis. The risk is not that they sell in panic. It is that they never revisit the position''s size or purpose at all.</p>

