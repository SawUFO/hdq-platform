<h2>Why a Hormuz Deal Now Cuts Twice Against the Loonie</h2>
<p>The first U.S.-Iran shuttle talks in months took place at the United Nations this week, and neither side has yet spelled out a change in position. Daniela Hathorn, a senior market analyst quoted by The National, estimated that a credible agreement to reopen Hormuz, combined with recovering Saudi exports, could push Brent toward the low $90s.</p>
<p>Lower crude weakens Canadian terms of trade directly. It also removes the main support for a Bank of Canada hike, because the October 28 hike case in Ottawa rests on oil. The Fed case rests on U.S. demand and a hot PMI, so it survives a peace deal intact.</p>
<p>The rate gap between the two countries would widen at the same moment the commodity support drops out. One diplomatic headline delivers two separate blows to the Canadian dollar. The failure scenario is the partial offset: renewed disruption lifts crude and revives Bank of Canada hike odds, narrowing the gap.</p>
<p>For Canadian portfolios carrying unhedged U.S. dollar exposure, that exposure now behaves as a hedge against peace rather than against escalation.</p>
<h2>The TSX Resource Hedge Split in Two</h2>
<p>The S&amp;P/TSX Composite was down 1.23% near 35,889 late in the session, on course for its steepest one-day decline in about two weeks. Energy and mining together account for more than 36% of the index by market capitalization, according to LSEG data, and that weight is usually described as a single commodity hedge. Wednesday showed it is two opposing hedges.</p>
<p>By midday the TSX gold subgroup was down 3.8% and materials down 3.5%, while energy had added just 0.7% against a near 4% rally in Brent. Spot gold fell 1.76% to $4,280 and silver 3.96% to $64.27 by early afternoon, both pressed by a U.S. dollar index at its highest since July 30 and by rising hike odds. Gold is now down about 7.3% over the past month.</p>
<p>The Composite gave back more than half of its post-hike rebound in a single session, and the late-session level sits roughly 1,070 points below the August 25 closing high.</p>
