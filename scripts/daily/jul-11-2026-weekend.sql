<h2>Why Gold Fell When the War Widened</h2>

<p>The clearest evidence that this is not a repeat of February sits in the gold market. Gold is the textbook safe-haven asset, the trade that is supposed to catch a bid whenever geopolitical risk widens. Instead it fell about 1.5 percent on the week, even as Iran extended the conflict to a fourth country for the first time.</p>

<p>The reason is not that the war stopped mattering. It is that the Federal Reserve is now competing with the war for control of the story. Minutes from the Fed''s latest meeting showed several policymakers favoured a rate hike before the committee ultimately held rates steady, and markets are now pricing a near 60 percent chance of a September increase. A Fed that hikes means a stronger U.S. dollar and a higher real rate, both of which weigh directly on a non-yielding asset like gold. This week, that mechanism dominated the safe-haven bid.</p>

<h2>The Canadian Side of the Ledger</h2>

<p>Statistics Canada added a wrinkle to the same story on Friday. Employment rose by 18,200 in June, well above the 10,000 consensus, and the unemployment rate fell to 6.5 percent, its lowest level in nearly two years. The data landed as the last major release before the Bank of Canada''s blackout period ahead of its July 15 decision, and it removed any remaining case for a near-term cut. The Government of Canada five-year yield closed at 3.18 percent on July 8, and the ten-year touched 3.55 percent, its highest level since May.</p>

<p>The Canadian dollar strengthened through the week on the back of that data, even as the geopolitical backdrop deteriorated. That is the same decoupling showing up in a second asset class: a domestic labour print doing more work on the currency than a war that just added a fourth country to its target list.</p>

