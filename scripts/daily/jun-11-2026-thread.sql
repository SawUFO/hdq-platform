<h2>The Gap Between Headline and Core Is the Only Number That Matters Now</h2>

<p>The morning''s Economy Desk established the BoC''s analytical frame: core inflation, not headline, determines the rate path. The Bank has said it will look through energy-driven headline acceleration. US core CPI at 2.9% in May, up a tenth from April but running well below the 4.2% headline, confirms that the energy shock has not yet bled into broader pricing. That is the BoC''s permission structure for the hold.</p>

<p>The Behaviour Desk identified the psychological trap: clients are experiencing the 4.2% US headline as their inflation reality while the Bank is watching a 2.9% core. The gap creates advisor friction. Clients ask why rates are not rising when prices are up. The correct answer is that the Bank is watching the right number, but the right number is the one they cannot see at the gas pump.</p>

<p>The afternoon''s deal signal changes the probability distribution on how long the gap persists. If Hormuz reopens, energy falls back, headline converges toward core, and the BoC''s five-hold plateau ends not with a hike but with a cut. The GoC 5-year, which has been drifting up on hike expectations, reverses. Fixed mortgage rates follow. The 2026-2027 renewal wall, which the Tax Desk quantified this morning in terms of specific client household exposure, becomes materially less dangerous than it appeared at 10 AM.</p>

<p>This is a conditional chain, not a base case. Iran has not confirmed the deal. The Strait remains declared closed by Tehran. US Central Command continues to deny the closure is operative. The market has been through this cycle before: ceasefire signal, oil drops, deal collapses, oil spikes. The correct framing is not "deal incoming" but "hike probability has declined in the past 26 minutes." That is what the bond market is processing right now.</p>

