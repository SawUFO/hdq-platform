<p>The bond market has not fully priced this. Bond markets currently assign a 5% probability of a June 10 hike, per Nesto''s OIS analysis. That is a stub number, a placeholder. It reflects the April 29 hold decision and the conditional language Macklem used. What it does not yet reflect is the specific outcome today: Trump rejecting Iran''s proposal, WTI closing above $97, and the peace timeline extending from "weeks" to "indefinite."</p>

<p>The five-year Government of Canada bond yield will be the tell. If it begins moving meaningfully higher in the next two sessions, the June 10 hike probability will reprice. The advisors who are watching the oil story through a geopolitical lens are watching the wrong variable. The variable that matters for Canadian portfolios is the GoC five-year yield and what it does to fixed mortgage rates over the next three weeks.</p>

<h2>Carney''s "Fortress North America" Offer and What It Means for Canadian Energy Stocks</h2>

<p>On Saturday, May 9, Prime Minister Carney told the Global Progress Action Summit in Toronto that Canada is open to "deeper integration" with the United States in certain sectors, explicitly naming "fortress North America" as a framework Canada has placed on the table ahead of the July 1 CUSMA review. His language was the clearest indication yet that Canadian energy and critical minerals are being offered as a trade concession in exchange for a stable trade agreement.</p>

<p>Read that alongside today''s oil data. Canadian energy stocks traded higher Monday, lifted by WTI''s bounce. But the Carney signal introduces a second-order consequence that is moving in the opposite direction from the near-term oil price support. If Canada offers the U.S. preferential access to Canadian energy under a "fortress North America" framework, that access likely involves pricing mechanisms, supply guarantees, or regulatory alignment that constrains the terms on which Canadian producers sell. The upside from higher WTI is not fully the Canadian energy sector''s to capture if a portion of that production is effectively earmarked for U.S. integration at negotiated terms.</p>

