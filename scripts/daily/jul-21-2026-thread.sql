<h2>Why the Anchor Broke Today and Not Ten Days Ago</h2>

<p>This morning''s Behavioural desk read gold''s flatness through anchoring bias and the disposition effect. Investors fixed on January''s $5,608.35 record were struggling to update on a slow, grinding conflict that kept producing a similar kind of headline night after night. That framing explains the ten days that preceded today. It does not explain today itself.</p>

<p>What changed was not the intensity of the news. It was its geography. Markets had priced ten nights of Hormuz adjacent strikes into a stable trading range. They had not priced a fourth front opening on the Caspian coast, a country whose oil infrastructure has nothing to do with Iran and everything to do with global seaborne supply math. WTI gained 2.20 per cent to $84.29, its highest close since June 12. Equities absorbed the same headline far more calmly, with the TSX, S&amp;amp;P 500, Dow, and Nasdaq all higher by less than either commodity on a percentage basis. When the safe haven and the supply channel both move harder than the equity channel on the same day, that reads as a genuine widening of physical risk, not a routine risk on rotation.</p>

<h2>What Monday''s Selloff Actually Was, and What Tomorrow Tests</h2>

<p>Monday''s 304 point TSX decline was almost entirely a banking story. CIBC fell 2.6 per cent, TD Bank 2.3 per cent, Scotiabank 2.3 per cent, RBC 2.1 per cent, and BMO 1.9 per cent, a rare instance of all five majors moving in lockstep on the week''s bond yield reaction. Today''s rebound is not those same banks recovering that ground. It is energy and base metal names doing the lifting, while the rate sensitive sectors that fell Monday have not been the story of Tuesday''s tape.</p>

<p>Monday''s decline is worth revisiting on its own terms, because it clarifies what today''s rebound is not.</p>
