<h2>The Pattern Investors Are Matching Against</h2>

<p>This is not the first time a Trump statement has declared the truce finished. Since the memorandum of understanding was signed June 17, there have been several distinct moments when the ceasefire looked over: Iran restricting Hormuz transit, missile fire at commercial shipping, and now two consecutive nights of direct strikes. Each episode produced an initial spike in oil and a pullback in equities, followed by a fade within one to three sessions as the conflict failed to widen further.</p>

<p>Amos Tversky and Daniel Kahneman''s 1974 work on judgment under uncertainty described the mechanism at work here. The representativeness heuristic leads people to judge the probability that an event belongs to a category, in this case events resembling prior temporary flare ups, rather than by re-evaluating the evidence directly in front of them. Each new escalation gets compared not to its own severity but to how closely it resembles the pattern of prior escalations that resolved without lasting portfolio damage. The comparison, not the content, is doing the work.</p>

<p>The trouble with pattern matching against a small, recent sample is that the sample itself has been getting worse. Wednesday''s strikes were smaller than Thursday''s. Iran''s retaliation against three Gulf states at once on Thursday had no precedent earlier in the conflict. Rystad Energy''s head of geopolitical analysis, Jorge Leon, said the events of the past several days significantly weaken any confidence that the current 60 day truce can still evolve into a permanent peace agreement. That assessment came from an energy analyst reading the facts. It has not yet come from the tape.</p>

