<h2>Why the Rate Jumps to 6.14% Instead of 5.60%</h2>

<p>British Columbia''s 2025 budget, tabled February 17, 2026, raised the lowest personal income tax rate from 5.06% to 5.60% for the 2026 taxation year, applying to the first $50,363 of taxable income. The change took effect retroactively to January 1, but the CRA''s January T4127 edition had already been finalized using the old 5.06% rate, since the BC budget had not yet been introduced.</p>

<p>The result was six months of underwithholding relative to the client''s actual 2026 liability. The July T4127 edition corrects for this by applying a prorated rate of 6.14% to BC payroll income for the second half of the year, high enough that six months at 6.14% plus six months at 5.06% averages out to approximately the correct 5.60% annual liability. BC also raised its basic tax reduction from $562 to $690 for 2026 and increased the basic personal tax credit percentage from 5.06% to 5.60%, both of which partially offset the higher withholding for lower income employees.</p>

<h2>Who Actually Feels This</h2>

