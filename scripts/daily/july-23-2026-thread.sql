<h2>Gold''s Refusal to Rally Is the More Useful Signal</h2>
<p>If this were unfolding as a pure fear event, the kind that sent gold higher through the earlier stages of the Hormuz conflict, gold should have caught a bid alongside oil today. It did the opposite. The August contract fell $97.20 to $4,054.70 an ounce even as the tail risk this morning''s Geopolitical desk flagged turned real and equities sold off broadly.</p>

<p>This morning''s Behavioural desk warned that the TSX''s push toward its record this week was narrow, carried by gold miners and energy names, and cautioned against extrapolating that pattern forward through the availability heuristic. Today''s session did not extend the pattern. It broke it. Gold miners fell alongside the banks, and the metal itself moved against the escalation rather than with it.</p>

<p>The mechanism is the one this morning''s Economy desk was already tracking. Fed hike odds for the July 29 decision had faded from a peak above 46% earlier this month to under 17% by Tuesday, but oil''s continued climb left the Bank of Canada''s own calculus unchanged regardless of what Washington does first. A supply-driven oil spike reads as an inflation shock, not a safety trade, and inflation shocks pull yields higher rather than pulling capital into gold. The U.S. 10-year Treasury yield stood at 4.697% Thursday, and Deutsche Bank''s Jim Reid noted directly that the combination of a shipping attack and a fresh leg higher in oil had revived speculation about further rate hikes rather than rate relief.</p>

<p>WTI and gold moved in the same direction for most of the past month, and today marks the sharpest split between the two since the ceasefire, with oil breaking higher on the shipping attack while gold gave back Wednesday''s gain entirely.</p>
