<h2>Why Wednesday''s Language Matters More Than Wednesday''s Decision</h2>

<p>The Bank of Canada''s April MPR built its inflation trajectory on an assumption that Brent crude would average around $90 per barrel in Q2 and decline toward $75 by mid-2027. Brent crossed $98 on Monday morning before settling near $94. The BoC''s April forecast saw CPI peaking near 3% in April, declining to 2.5% by June. April CPI came in at 2.8%. May CPI does not release until June 22, ten days after Wednesday''s decision.</p>

<p>Macklem and Rogers will hold at 2.25%. That is not the question. The question is what language accompanies the hold. The April statement signalled explicitly that both cuts and hikes remain on the table. Bond markets currently price only a 4% probability of a hike at any meeting through July. Interest rate swap markets, according to Globe and Mail data from the past week, are now pricing between two and three quarter-point hikes by the end of 2026, starting in October, which is a material shift from where they were in May.</p>

<p>The trajectory the market is assigning to the BoC over the next six months now sits squarely on a Hormuz resolution timeline. A durable ceasefire deal that gradually reopens the Strait would ease oil prices, ease headline CPI, and give Macklem a clean path to remaining on hold through year-end. The data from Monday''s session, where oil was up 4% in Asian trading and still settled above $91 after a partial ceasefire signal, suggests that resolution is not yet visible in the data the BoC will have in hand on Wednesday.</p>

<p>The Baystreet analysis from earlier this week put it cleanly: a credible deal that reopens the Strait would likely send oil lower and USD/CAD higher in the near term, as the energy premium supporting the Loonie unwinds faster than the interest rate differential narrows. The Loonie closed at 1.3951 to the U.S. dollar on Monday, its weakest level in eight weeks. Canada''s Q1 GDP contracted at an annualized 0.1%, a second consecutive quarterly decline. CAD weakness and economic contraction are pulling in the same direction as a hold. But 2.8% CPI and $91 oil are pulling in the other direction. Macklem will have to acknowledge both.</p>

<p>TSX Energy''s year-to-date performance against the BoC''s rate path expectations, against the backdrop of the WTI price arc since February, is the cross-desk picture that ties today''s recovery narrative to Wednesday''s policy question. The closing data from Monday quantifies the gap between where the BoC assumed oil would be and where it actually is, and that gap is the only thing in the June 10 statement that markets do not yet have a clear view on.</p>

