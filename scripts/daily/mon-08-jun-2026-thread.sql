<h2>The Contradiction the Market Is Accepting</h2>

<p>The market''s implicit position on Monday was internally contradictory: oil is high enough to make energy stocks attractive, but not high enough to force the BoC to hike. Both conditions can''t hold indefinitely. The BoC''s April MPR baseline assumed Brent crude would average around $90 per barrel in Q2, then decline gradually toward $75 by mid-2027. Brent opened Monday above $98 before settling near $94. WTI settled near $91. The BoC''s own inflation projections from April forecast CPI peaking near 3% in April before declining to 2.5% by June. April came in at 2.8%. May CPI releases June 22, two weeks after Wednesday''s decision.</p>

<p>The composite is betting that Wednesday''s decision is a hold and Macklem''s language stays in "wait and see" territory. Bond markets are pricing approximately 96% probability of no change, with only 4% implied odds on a hike. RBC Economics expects a fifth consecutive hold, noting that while headline CPI has moved above the 2% target, core inflation measures surprised to the downside in April, and there is little evidence of oil-driven energy inflation filtering into broader goods and services.</p>

<p>That is a reasonable read. The problem is that it is a read built on April data, with May data still two weeks away and the Hormuz closure still functionally in place.</p>

<h2>What the Hormuz Chart Shows That the Recovery Narrative Is Missing</h2>

