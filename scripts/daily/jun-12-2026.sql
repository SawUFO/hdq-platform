<h2>The TFSA in June: The Overlooked Window</h2>

<p>The 2026 TFSA annual contribution limit is $7,000, the third consecutive year at that level. For a Canadian resident eligible since 2009, cumulative room is $109,000. The account is the only structure in Canada where capital gains, dividends, and interest all compound and withdraw completely tax-free, and where no future inclusion rate change can reach.</p>

<p>Mid-year is structurally the best time to surface the TFSA conversation with clients who have not yet contributed for 2026. January contributions attract attention because advisors send reminders. The clients who did not act in January have not lost the room: unused 2026 room carries forward indefinitely. The June conversation has a different texture. The client who has $7,000 sitting in cash, or sitting in a non-registered account earning taxable interest, can move it today. A client who withdrew from their TFSA during 2025 for any reason has that withdrawal amount restored as contribution room on January 1, 2026.</p>

<p>The RRSP contribution limit for 2026 is $33,810. The RRSP deadline for 2025-tax-year contributions was March 2, 2026, which has passed. Clients making 2026-tax-year contributions to their RRSP should be reminded that the deduction applies on their 2026 return, filed in spring 2027. Contributions made now reduce 2026 taxable income, which is the relevant planning horizon for clients with variable income this year.</p>

