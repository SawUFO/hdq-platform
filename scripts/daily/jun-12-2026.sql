<p>Canada''s unemployment rate declining to 6.6%, April GDP tracking at +0.4%, and the Bank of Canada holding at 2.25% citing mixed signals rather than crisis: these are not the ingredients of the 2008 experience the brain is replaying. The data and the narrative have diverged. The two-week period following an availability-triggering event is when clients are most likely to make reactive portfolio decisions, and when an advisor-initiated conversation carries the highest interruption value.</p>

