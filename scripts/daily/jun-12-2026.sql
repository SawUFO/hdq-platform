<h2>The Word Arrived, and the Brain Did the Rest</h2>

<p>The availability heuristic, first described by Amos Tversky and Daniel Kahneman in their 1973 paper "Availability: A Heuristic for Judging Frequency and Probability," describes a cognitive shortcut people use when estimating the likelihood or severity of events: they rely on how easily a vivid, emotionally resonant example comes to mind. The easier the recall, the higher the perceived probability.</p>

<p>The word "recession" carries an enormous availability load. Every Canadian over 40 has a mental image attached to it: 2008-09, layoffs, portfolio losses, foreclosures, fear. The word does not describe a quarter-point contraction in a GDP table. It describes a felt experience. When Statistics Canada confirmed the technical definition was met, the word moved from the economics pages to the front page, from financial media to social media, from headlines to conversations at kitchen tables. Searches for "what is a recession" surged across the country within hours of the May 29 report.</p>

<p>Tversky and Kahneman found that when a concept is easy to bring to mind, people systematically overestimate both its frequency and its severity. The clients who saw the May 29 headlines did not update their economic probability estimates by 0.1 percentage points. They recalled 2008. They recalled what that felt like. Their brains did not experience a statistical rounding issue. They experienced the emotional signature of a recession.</p>

<h2>What the Data Actually Said</h2>

<p>The GDP report itself contained contradictions the headline masked. On a quarter-over-quarter basis (not annualized), GDP was unchanged at 0.0%. Services-producing industries grew 0.3%. Household spending rose 0.4% in Q1 after a 0.7% increase in Q4. Capital Economics called the contraction "trade-induced," arguing it reflected measurement distortions from US tariff uncertainty rather than genuine consumer retrenchment. Statistics Canada''s own early estimate for April GDP showed a sharp rebound of +0.4%.</p>

<p>Then, seven days after the recession headline, Statistics Canada released the May Labour Force Survey. Employment rose by 88,000, almost nine times the 10,000 consensus forecast. Full-time employment alone rose 154,000. The unemployment rate fell to 6.6% from 6.9%. BMO''s chief economist said the report "should silence the recession crowd." The data, viewed in full, described a technical recession that may already be over.</p>

<p>The availability heuristic does not weigh this full picture. It anchors to the first vivid, emotionally loaded signal. The word "recession" was that signal, and it arrived before the May jobs print.</p>

<h2>The Anchoring That Follows Availability</h2>

<p>Tversky and Kahneman identified anchoring as a companion phenomenon: once a reference point is established, subsequent judgments are adjusted from that anchor, but insufficiently. Clients who anchored on the recession label on May 29 have not simply updated that anchor by +88,000 jobs and a rising GDP trajectory. The anchor is stickier than the incoming data that should dislodge it.</p>

<p>Kliger and Kudryavtsev, in their 2010 paper in the Journal of Behavioral Finance, tested this directly: availability effects on investor reactions to new information are asymmetric. Negative, emotionally salient information activates availability strongly and persists; subsequent positive information adjusts the signal but does not fully reverse it. The architecture of the bias means the recession label is still doing work inside a client''s mental model even as the underlying data improves.</p>

<p>This is the window. The client who anchored on the recession word two weeks ago has not yet had their frame corrected. They may be sitting on a portfolio decision they have not yet acted on, or they may be watching their account without context, interpreting every normal fluctuation as confirming evidence of the recession they are expecting.</p>

