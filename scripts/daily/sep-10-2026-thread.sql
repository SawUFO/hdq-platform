<h2>Why the Tariff Story No Longer Explains the Yield Story</h2>

<p>This matters because the Economy Desk''s framing over the past two sessions, that Canadian yields are pricing Ottawa-Washington trade risk, only partially survives today''s close. Some of Thursday''s 5.6 basis points is genuinely global term-premium repricing that has nothing to do with the tariff dispute and would have happened to Canadian bonds regardless of what Ottawa and Washington do next. That portion does not unwind if the trade dispute cools. It is a bond-market plumbing event, not an inflation-expectations event.</p>

<p>The distinction has a concrete date attached to it. Friday''s U.S. CPI print is the input markets are watching for next week''s September 16 Federal Reserve decision, where CME FedWatch currently prices a rate hike near 60% odds under Chair Kevin Warsh. Thursday''s producer price data came in exactly at the 0.4% consensus, no surprise either way. If Friday''s CPI also lands soft and the Fed leans toward holding, advisors should expect Canadian yields to ease only partially. The buyback-driven portion of today''s move is sticky. A soft CPI print resolves the inflation-expectations half of Thursday''s yield jump. It does not resolve the supply half.</p>

<h2>The Loonie That Should Have Moved and Did Not</h2>

<p>A second signal sits in the currency market. The Canadian dollar traded flat near 1.381 against the U.S. dollar on Thursday, essentially unchanged from Wednesday. That stillness is not the absence of pressure. It is two pressures cancelling out. A widening Canada-U.S. yield gap and a worsening trade dispute would each independently weaken the loonie on their own. Both were present Thursday. What offset them was oil crossing $100 on both benchmarks, WTI and Brent, at the same time, a two-benchmark confirmation of the risk premium that handed Canada''s oil-exporting terms of trade an almost precisely matching tailwind.</p>

<p>The practical read for tomorrow: CAD''s calm is not a signal that Thursday''s pressures were mild. It is a signal that they were large and offsetting. If oil pulls back from $100 on any de-escalation headline while the global bond selloff persists, or if Friday''s CPI triggers a Fed-driven Treasury rally that Canada''s tariff-inflation risk does not follow, the two forces holding CAD in place stop moving together. That is the scenario in which the loonie''s next move is larger than Thursday''s near-zero change suggests, in either direction.</p>

